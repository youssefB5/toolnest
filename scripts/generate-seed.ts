// Generates supabase/seed/seed.sql from the typed registry (single source of truth).
// Run: npm run seed:sql   (node --experimental-strip-types)
import { writeFileSync, mkdirSync } from 'node:fs';
import { CATEGORIES } from '../src/registry/categories.ts';
import { IMAGE_TOOLS } from '../src/registry/data/image.ts';
import { PDF_TOOLS } from '../src/registry/data/pdf.ts';
import { TEXT_TOOLS } from '../src/registry/data/text.ts';
import { DEVELOPER_TOOLS } from '../src/registry/data/developer.ts';
import { CALCULATOR_TOOLS, CONVERTER_TOOLS, PRODUCTIVITY_TOOLS, SECURITY_TOOLS } from '../src/registry/data/misc.ts';

const TOOLS = [...IMAGE_TOOLS, ...PDF_TOOLS, ...TEXT_TOOLS, ...DEVELOPER_TOOLS, ...CONVERTER_TOOLS, ...CALCULATOR_TOOLS, ...PRODUCTIVITY_TOOLS, ...SECURITY_TOOLS];

const q = (s: string | null | undefined) => (s === null || s === undefined ? 'null' : `'${String(s).replace(/'/g, "''")}'`);
const arr = (a: string[]) => `array[${a.map(q).join(', ')}]::text[]`;

const lines: string[] = [];
lines.push('-- GENERATED by scripts/generate-seed.ts — do not edit by hand.');
lines.push('-- Safe to re-run: existing rows are left untouched (on conflict do nothing).');
lines.push('begin;');
lines.push('');
lines.push('insert into public.categories (id, slug, icon, title, description, sort_order, is_visible) values');
lines.push(
  CATEGORIES.map((c) => `  (${q(c.id)}, ${q(c.slug)}, ${q(c.icon)}, ${q(c.title)}, ${q(c.description)}, ${c.order * 10}, true)`).join(',\n') + '\non conflict (id) do nothing;',
);
lines.push('');
lines.push('insert into public.tools (id, slug, implementation_key, category_id, icon, title, short_description, keywords, status, is_enabled, is_featured, is_popular, sort_order, published_at) values');
lines.push(
  TOOLS.map(
    (t, i) =>
      `  (${q(t.id)}, ${q(t.slug)}, ${q(t.implementation)}, ${q(t.category)}, ${q(t.icon)}, ${q(t.title)}, ${q(t.short)}, ${arr(t.keywords)}, 'published', true, ${!!t.featured}, ${!!t.popular}, ${(i + 1) * 10}, ${q(t.addedAt)}::timestamptz)`,
  ).join(',\n') + '\non conflict (id) do nothing;',
);
lines.push('');
lines.push('-- Registry French/Arabic titles and short descriptions, published as translations.');
lines.push('insert into public.translations (locale, entity_type, entity_id, field, value, status) values');
const tr: string[] = [];
for (const t of TOOLS)
  for (const loc of ['fr', 'ar'] as const) {
    const x = t.i18n?.[loc];
    if (!x) continue;
    tr.push(`  (${q(loc)}, 'tool', ${q(t.id)}, 'title', ${q(x.title)}, 'published')`);
    tr.push(`  (${q(loc)}, 'tool', ${q(t.id)}, 'short_description', ${q(x.short)}, 'published')`);
  }
for (const c of CATEGORIES)
  for (const loc of ['fr', 'ar'] as const) {
    const x = c.i18n?.[loc];
    if (!x) continue;
    tr.push(`  (${q(loc)}, 'category', ${q(c.id)}, 'title', ${q(x.title)}, 'published')`);
    tr.push(`  (${q(loc)}, 'category', ${q(c.id)}, 'description', ${q(x.description)}, 'published')`);
  }
lines.push(tr.join(',\n') + '\non conflict (locale, entity_type, entity_id, field) do nothing;');
lines.push('');
lines.push(`insert into public.homepage_sections (id, is_enabled, sort_order) values
  ('hero', true, 1), ('popular', true, 2), ('categories', true, 3), ('recent', true, 4), ('why', true, 5), ('faq', true, 6), ('seo', true, 7)
on conflict (id) do nothing;`);
lines.push('');
lines.push(`insert into public.advertisement_slots (id, is_enabled, min_height) values
  ('header', false, 90), ('home', false, 250), ('category', false, 250), ('tool', false, 250), ('footer', false, 90)
on conflict (id) do nothing;`);
lines.push('');
lines.push(`insert into public.site_settings (key, value) values
  ('ads', '{"enabled": false, "provider": "none", "adsenseClient": "", "requireConsent": true}'::jsonb),
  ('general', '{"maxUploadMb": 50, "maintenanceBanner": "", "showRecentlyAdded": true}'::jsonb)
on conflict (key) do nothing;`);
lines.push('');
lines.push('commit;');

mkdirSync('supabase/seed', { recursive: true });
writeFileSync('supabase/seed/seed.sql', lines.join('\n') + '\n');
console.log(`seed.sql written: ${CATEGORIES.length} categories, ${TOOLS.length} tools, ${tr.length} translations`);
