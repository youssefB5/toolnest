// Creates test accounts on the LOCAL Supabase stack (`npx supabase start`) and
// writes their credentials to .env.test.local (git-ignored). Refuses any non-local URL.
// Usage: node scripts/setup-local-supabase.mjs
import { execFileSync } from 'node:child_process';
import { randomBytes } from 'node:crypto';
import { writeFileSync } from 'node:fs';

const status = JSON.parse(execFileSync('npx', ['supabase', 'status', '-o', 'json'], { encoding: 'utf8', shell: true }).replace(/^[^{]*/, ''));
const api = status.API_URL;
if (!/^http:\/\/(127\.0\.0\.1|localhost):\d+$/.test(api)) throw new Error(`Refusing: ${api} is not a local Supabase stack.`);
const service = status.SERVICE_ROLE_KEY; // local demo key, used only by this setup script
const anon = status.ANON_KEY;

const pw = () => `Tn-${randomBytes(12).toString('base64url')}9a`;
const users = {
  OWNER: { email: 'owner@toolnest.test', password: pw(), role: 'owner' },
  ADMIN: { email: 'admin@toolnest.test', password: pw(), role: 'admin' },
  EDITOR: { email: 'editor@toolnest.test', password: pw(), role: 'editor' },
  USER: { email: 'user@toolnest.test', password: pw(), role: null }, // signed-in but not an administrator
};

const h = { apikey: service, Authorization: `Bearer ${service}`, 'Content-Type': 'application/json' };
const list = await (await fetch(`${api}/auth/v1/admin/users?per_page=200`, { headers: h })).json();
for (const u of Object.values(users)) {
  const existing = (list.users ?? []).find((x) => x.email === u.email);
  if (existing) await fetch(`${api}/auth/v1/admin/users/${existing.id}`, { method: 'DELETE', headers: h });
  const r = await fetch(`${api}/auth/v1/admin/users`, { method: 'POST', headers: h, body: JSON.stringify({ email: u.email, password: u.password, email_confirm: true }) });
  const j = await r.json();
  if (!r.ok) throw new Error(`create ${u.email}: ${JSON.stringify(j)}`);
  u.id = j.id;
}

// Role rows are inserted through the database container (same path as admin-onboarding.sql).
const sql = Object.values(users)
  .filter((u) => u.role)
  .map((u) => `insert into public.admin_users (user_id, email, role) values ('${u.id}', '${u.email}', '${u.role}') on conflict (user_id) do update set role = excluded.role, is_active = true;`)
  .join('\n');
const container = execFileSync('docker', ['ps', '--filter', 'name=supabase_db_', '--format', '{{.Names}}'], { encoding: 'utf8' }).trim().split('\n')[0];
execFileSync('docker', ['exec', '-i', container, 'psql', '-U', 'postgres', '-d', 'postgres', '-v', 'ON_ERROR_STOP=1'], { input: sql, stdio: ['pipe', 'inherit', 'inherit'] });

const env = [
  '# Local Supabase test stack — generated by scripts/setup-local-supabase.mjs (never commit)',
  `SUPABASE_TEST_URL=${api}`,
  `SUPABASE_TEST_ANON_KEY=${anon}`,
  ...Object.entries(users).flatMap(([k, u]) => [`SUPABASE_TEST_${k}_EMAIL=${u.email}`, `SUPABASE_TEST_${k}_PASSWORD=${u.password}`]),
  '',
].join('\n');
writeFileSync('.env.test.local', env);
console.log(`Created ${Object.keys(users).length} local test users; credentials written to .env.test.local`);
